#ifndef ATTITUDE_H_
#define ATTITUDE_H_

#include "zf_common_headfile.h"

typedef struct
{
    float roll;         // 横滚角，车体左右倾，单位 deg
    float pitch;        // 俯仰角，车体前后倾，单位 deg
    float yaw;          // 连续航向角，永不清零，单位 deg
    float yaw_wrapped;  // 显示用航向角，范围 (-180, 180]

    float roll_rate;    // 机体系gyro_x，单位 deg/s，不等同一般姿态下的欧拉Roll变化率
    float pitch_rate;   // 机体系gyro_y，单位 deg/s；Pitch控制另作欧拉角速度投影
    float yaw_rate;     // 机体系gyro_z，单位 deg/s，不等同一般姿态下的欧拉Yaw变化率
} attitude_t;

extern attitude_t att;

typedef struct
{
    float acc_norm;     // 加速度模长，单位 g
    float bias_z;       // A+ 在线体坐标 Z 零偏估计（不含启动均值），单位 rad/s
    float acc_weight;   // A+ 加计修正权重
    float period_us, update_us, max_update_us; // STM 时序诊断，须上板实测
    uint8 is_static;    // 内部零偏学习判定，不是电机安全许可
    uint8 acc_valid;    // 加速度校正有效标志
} att_diag_t;

extern att_diag_t att_diag;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化 A+ r10h 六轴姿态解算状态
// 参数说明     void
// 返回参数     void
// 使用示例     attitude_init();
//-------------------------------------------------------------------------------------------------------------------
void attitude_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     使用 IMU 原始数据更新车体系角速度
// 参数说明     void
// 返回参数     void
// 使用示例     attitude_update_rate();
//-------------------------------------------------------------------------------------------------------------------
void attitude_update_rate(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     每 1 ms 发布 A+ 欧拉角（核心每 1 ms 更新）
// 参数说明     void
// 返回参数     void
// 使用示例     attitude_update();
//-------------------------------------------------------------------------------------------------------------------
void attitude_update(void);

// 每 1 ms 六轴采样后调用；不可丢帧后补调用。
void attitude_tick1ms(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检查姿态解算冷启动收敛状态
// 参数说明     void
// 返回参数     uint8           1 表示收敛完成，0 表示尚未完成
// 使用示例     uint8 ready = attitude_converged();
//-------------------------------------------------------------------------------------------------------------------
uint8 attitude_converged(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检查四元数是否发生过发散
// 参数说明     void
// 返回参数     uint8           1 表示发生过发散，0 表示正常
// 使用示例     uint8 fault = attitude_diverged();
//-------------------------------------------------------------------------------------------------------------------
uint8 attitude_diverged(void);

#endif
